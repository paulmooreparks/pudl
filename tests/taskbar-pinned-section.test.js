const assert = require('assert/strict');
const { launch, ROOT, out } = require('./lib');
(async () => {
  const browser = await launch();
  try {
    const page = await browser.newPage({viewport:{width:1440,height:950}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(ROOT+'/mockups/pinned-section.html');
    await page.locator('.win-bar [data-win-menu-id="view"]').waitFor();
    assert.equal(await page.locator('.win-taskbar-heading').count(),1);
    assert.ok(await page.locator('.win-bar [data-win-pin-running="false"]').evaluateAll(ns=>ns.every(n=>getComputedStyle(n,'::before').display==='none')),'dormant destinations have no individual pin or running mark');
    assert.equal(await page.locator('.task-strip,[data-site-menu-pin]').count(),0,'the host authors no pin-specific controls or section');
    const snapshot=await page.evaluate(()=>pudlWindows.taskbarState());
    assert.ok(snapshot.references.some(r=>r.provider==='pudl-site-menus'));
    const viewId=await page.evaluate(()=>pudlMenubar.siteMenuDestinationId('view'));
    assert.equal(await page.evaluate(id=>pudlWindows.configureTaskbar({destinations:[],pins:[id],references:[{id,provider:'other'}]}),viewId),false,'conflicting menu provider references are rejected atomically');
    await page.reload();
    await page.locator('.win-bar [data-win-menu-id="view"]').waitFor();
    assert.deepEqual(await page.evaluate(()=>pudlWindows.taskbarState()),snapshot,'menu references restore through ordinary preferences');
    await page.evaluate(()=>pudlWindows.open('terminal'));
    await page.locator('.win[data-win="terminal"]').waitFor();
    await page.evaluate(()=>{
      document.querySelector('[data-win-layer]').setAttribute('data-win-taskbar-reorder','');
      const state=pudlWindows.taskbarState();
      window.orderBefore=state.order;
      window.crossMove=pudlWindows.reorderTaskbarEntry('pin:settings',{after:'terminal'});
    });
    assert.equal(await page.evaluate(()=>crossMove),false);
    assert.deepEqual(await page.evaluate(()=>pudlWindows.taskbarState().order),await page.evaluate(()=>orderBefore));
    assert.equal(await page.locator('.win-taskbar-divider').count(),1);
    const before=await page.evaluate(()=>pudlWindows.taskbarState());
    assert.equal(await page.evaluate(()=>pudlWindows.configureTaskbar({destinations:[{id:'bare',label:'Bare command',kind:'command'}],pins:['bare']})),false);
    assert.equal(await page.evaluate(()=>pudlWindows.configureTaskbar({destinations:[{id:'empty-link',label:'Empty link',kind:'link'}]})),false,'link destinations require an address');
    assert.equal(await page.evaluate(()=>pudlWindows.configureTaskbar({providers:[{id:'pudl-site-menus',resolve:()=>({status:'unavailable'})}]})),false,'hosts cannot replace the built-in menu provider');
    assert.deepEqual(await page.evaluate(()=>pudlWindows.taskbarState()),before,'invalid kinds do not partially update preferences');
    await page.evaluate(()=>pudlWindows.open('editor'));
    await page.locator('.win #draft').focus();
    await page.evaluate(()=>document.getElementById('draft').setSelectionRange(2,8));
    await page.locator('.win-bar [data-win-menu-id="view"]').click();
    await page.getByRole('menuitem',{name:'Light theme',exact:true}).click();
    assert.equal(await page.locator('.win #draft').evaluate(n=>n===document.activeElement && n.selectionStart===2 && n.selectionEnd===8),true,'tear-off commands restore the content focus and selection');
    await page.locator('.win-bar [data-win-menu-id="view"]').focus();await page.keyboard.press('ArrowUp');
    await page.getByRole('menu',{name:'View',exact:true}).waitFor();
    assert.equal(await page.getByRole('menuitem',{name:'Dark theme',exact:true}).evaluate(n=>n===document.activeElement),true,'ArrowUp opens at the final menu row');
    await page.keyboard.press('ArrowLeft');await page.keyboard.press('ArrowRight');
    assert.equal(await page.getByRole('menu',{name:'View',exact:true}).isVisible(),true,'a tear-off does not navigate to unrelated menubar titles');
    await page.evaluate(()=>{document.querySelector('[data-menubar-source] [data-set-theme="dark"]').disabled=true;pudlMenubar.refresh();});
    assert.equal(await page.getByRole('menuitem',{name:'Dark theme',exact:true}).getAttribute('aria-disabled'),'true','open tear-off refreshes command availability');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.win-bar [data-win-menu-id="view"]').evaluate(n=>n===document.activeElement),true,'Escape returns to the ordinary menu taskbar entry');
    await page.setViewportSize({width:210,height:850});
    await page.waitForFunction(()=>!document.querySelector('.win-bar [data-win-menu-id="view"]').getClientRects().length);
    await page.locator('.win-bar-more:visible').click();
    await page.getByRole('menuitem',{name:'View, pinned menu',exact:true}).click();
    await page.getByRole('menu',{name:'View',exact:true}).waitFor();
    assert.equal(await page.locator('#menubar-panel').getAttribute('data-menu-anchor'),await page.locator('.win-bar-more').getAttribute('id'),'overflow uses the visible More anchor');
    await page.keyboard.press('Escape');await page.setViewportSize({width:1440,height:950});
    await page.evaluate(()=>{
      document.querySelector('[data-menubar-source] > [data-menu-glyph="eye"]').remove();pudlMenubar.refresh();
    });
    await page.waitForFunction(id=>document.querySelector('[data-win-pin="'+id+'"]').getAttribute('aria-disabled')==='true',viewId);
    assert.ok((await page.evaluate(()=>pudlWindows.taskbarState().pins)).includes(viewId),'unavailable saved menu membership survives');
    const unavailable=page.locator('.win-bar [data-win-pin="'+viewId+'"]');
    const bounds=await unavailable.boundingBox();await page.mouse.click(bounds.x+bounds.width/2,bounds.y+bounds.height/2,{button:'right'});
    await page.getByRole('menuitem',{name:'Unpin from taskbar',exact:true}).click();
    assert.equal(await unavailable.count(),0,'unavailable menu remains removable');
    await page.evaluate(()=>pudlWindows.taskbarState().pins.forEach(id=>pudlWindows.pinTaskbar(id,false)));
    assert.equal(await page.locator('.win-taskbar-heading,.win-taskbar-divider').count(),0,'empty section is omitted');
    assert.deepEqual(errors,[]);
    await page.screenshot({path:out('shared-pinned-section.png')});
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
