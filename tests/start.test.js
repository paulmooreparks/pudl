/* Start composes with the general menu script and leaves host state intact. */
const assert = require('assert/strict');
const { launch, ROOT, out } = require('./lib');
(async () => {
  const browser = await launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    for (const file of ['start.html', 'start-left.html']) {
      await page.goto(ROOT + '/samples/' + file);
      await page.waitForFunction(() => document.querySelector('[data-start]').matches(':popover-open'));
      const root = page.locator('[data-start]'), query = root.locator('[data-start-query]');
      await root.locator('[data-start-category-key="tools"]').click();
      assert.equal(await root.locator('[data-start-item]:visible').count(), 3);
      assert.ok(await root.evaluate(el => el.matches(':popover-open')), 'category click does not dismiss through pudl-menu');
      await query.fill('flowchart');
      assert.equal(await root.locator('[data-start-item]:visible').count(), 1);
      await query.press('ArrowDown');
      assert.equal(await page.evaluate(() => document.activeElement.querySelector('.start-name').textContent), 'Diagrams');
      await query.fill('unfindable');
      assert.equal(await root.locator('[data-start-empty]').isVisible(), true);
      await root.locator('#reset').click();
      assert.equal(await root.locator('[data-start-item]:visible').count(), 12);
      await root.locator('[data-start-category-key="pinned"]').click();
      assert.equal(await root.locator('[data-start-item]:visible').count(), 3);
      await page.goBack();
      await page.waitForFunction(() => pudlStart.state(document.querySelector('[data-start]')).category === '');
      await query.focus(); await query.press('Escape');
      assert.equal(await root.evaluate(el => el.matches(':popover-open')), false);
      assert.equal(await page.evaluate(() => document.activeElement.id), 'start');
      await page.locator('#start').press('ArrowDown');
      await page.waitForFunction(() => document.activeElement.hasAttribute('data-start-query'));
      const handle = root.locator('.split-handle'), first = root.locator('.split-pane').first();
      const width = (await first.boundingBox()).width;
      await handle.focus(); await handle.press('ArrowLeft');
      assert.ok((await first.boundingBox()).width < width, 'keyboard splitter resizes');
      const before = (await first.boundingBox()).width, box = await handle.boundingBox();
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
      await page.mouse.move(box.x + box.width / 2 - 24, box.y + box.height / 2, { steps: 3 }); await page.mouse.up();
      assert.ok((await first.boundingBox()).width < before - 16, 'pointer splitter resizes');
      await handle.press('Enter');
      for (const theme of ['light', 'dark']) {
        await page.evaluate(t => document.documentElement.dataset.theme = t, theme);
        await page.screenshot({ path: out(file + '-' + theme + '.png') });
      }
      await page.setViewportSize({ width: 390, height: 844 });
      await page.evaluate(() => document.documentElement.dir = 'rtl');
      const bounds = await root.boundingBox();
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
      await query.fill('draw');
      assert.equal(await root.locator('[data-start-item]:visible').count(), 1);
      await page.screenshot({ path: out(file + '-narrow-rtl.png') });
      await page.evaluate(() => { document.documentElement.style.fontSize = '32px'; });
      assert.ok(await root.locator('[data-start-query]').isVisible());
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.setViewportSize({ width: 1280, height: 850 });
      console.log('PASS ' + file + ' filtering, category history, dismissal, splitter, themes, RTL and enlarged text');
    }
    await page.goto(ROOT + '/tests/fixtures/start.html');
    await page.waitForFunction(() => window.pudlStart && pudlStart.state(document.getElementById('catalog')).count === 4);
    await page.locator('#open').click();
    await page.waitForFunction(() => document.activeElement.hasAttribute('data-start-query'));
    const positionBefore = await page.locator('#catalog').boundingBox();
    await page.addScriptTag({ url: ROOT + '/dist/pudl-menu.js' });
    await page.evaluate(() => dispatchEvent(new Event('resize')));
    const positionAfter = await page.locator('#catalog').boundingBox();
    assert.deepEqual(positionAfter, positionBefore, 'late menu loading does not take Start placement');
    await page.locator('#catalog [data-start-query]').press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'open', 'native pointer opener is retained');
    await page.locator('#open').click();
    await page.waitForFunction(() => document.activeElement.hasAttribute('data-start-query'));
    const result = await page.evaluate(async () => {
      const root = document.getElementById('catalog'), input = root.querySelector('[data-start-query]');
      const turn = () => new Promise(resolve => setTimeout(resolve, 0));
      window.changes = [];
      root.addEventListener('pudl:start-change', e => changes.push(e.detail));
      const address = location.href;
      pudlStart.setState(root, { query: 'draft', category: '' });
      const assertState = pudlStart.state(root);
      const searchCount = assertState.count;
      input.closest('form').requestSubmit();
      const commands = window.commands;
      const stayedOpen = root.matches(':popover-open');
      pudlStart.setState(root, { query: '', category: 'unknown' });
      const fallback = pudlStart.state(root).category;
      root.querySelector('[data-start-item][hidden]').hidden = false;
      await turn();
      const revealed = pudlStart.state(root).count;
      const list = root.querySelector('[data-start-items]');
      const row = document.createElement('li'); row.setAttribute('data-start-item', ''); row.setAttribute('data-start-category', 'tools');
      row.innerHTML = '<a class="md-item start-item" href="#live">Live destination</a>'; list.appendChild(row);
      await turn();
      const inserted = pudlStart.state(root).count;
      pudlStart.setState(root, { query: 'renamed' });
      row.querySelector('a').firstChild.data = 'Renamed destination';
      await turn();
      const renamed = pudlStart.state(root).count;
      pudlStart.setState(root, { query: '' });
      await turn();
      const mutations = []; const observer = new MutationObserver(records => mutations.push(...records));
      observer.observe(root, { subtree: true, childList: true, attributes: true, characterData: true });
      pudlStart.enhance(root); pudlStart.refresh(root); pudlStart.setState(root, pudlStart.state(root));
      /* These APIs draw synchronously. Read their records before yielding
         to independent popup and splitter work already queued by this test. */
      mutations.push(...observer.takeRecords()); observer.disconnect();
      await turn();
      const other = root.cloneNode(true); other.id = 'second'; other.removeAttribute('popover');
      other.querySelector('[data-start-items]').innerHTML = '<li data-start-item><a href="#other">Other</a></li>';
      document.body.appendChild(other); pudlStart.enhance(other); pudlStart.setState(other, { query: 'missing' });
      const independent = pudlStart.state(root).query === '' && pudlStart.state(other).count === 0;
      pudlStart.setState(root, { query: 'missing' });
      pudlStart.destroy(root);
      const cleaned = !root.querySelector('[data-start-filtered]') && pudlStart.state(root) === null;
      pudlStart.enhance(root);
      const restored = pudlStart.state(root).query === 'missing';
      pudlStart.setState(root, { query: '' });
      return { searchCount, commands, stayedOpen, fallback, revealed, inserted, renamed, writes: mutations.length, independent, cleaned, restored, noHistory: location.href === address };
    });
    assert.deepEqual(result, { searchCount: 1, commands: 1, stayedOpen: true, fallback: '', revealed: 5, inserted: 6, renamed: 1, writes: 0, independent: true, cleaned: true, restored: true, noHistory: true });
    console.log('PASS mixed commands, hidden rows, insertion, live text, unchanged refresh, independent instances and lifecycle');
    await page.locator('#catalog [data-start-query]').focus();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'command');
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Hidden', 'host-revealed item joins navigation');
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Renamed destination');
    await page.keyboard.press('End');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Renamed destination');
    await page.keyboard.press('Home'); await page.keyboard.press('ArrowUp');
    assert.equal(await page.evaluate(() => document.activeElement.hasAttribute('data-start-query')), true);
    await page.locator('#outside').click();
    assert.equal(await page.locator('#catalog').evaluate(el => el.matches(':popover-open')), false);
    assert.equal(await page.evaluate(() => document.activeElement === document.body || document.activeElement.id === 'outside'), true,
      'outside dismissal preserves native focus behavior without returning to Start');
    await page.evaluate(() => pudlStart.open(document.getElementById('catalog'), document.getElementById('open')));
    await page.locator('#catalog [data-start-query]').press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'open');
    assert.deepEqual(errors, []);
    console.log('PASS disabled actions skipped, outside dismissal, API focus return and no page errors');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
