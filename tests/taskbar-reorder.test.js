const { launch, ROOT, out } = require('./lib');
const assert = require('assert/strict');
(async () => {
  const b = await launch();
  const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  const url = ROOT + '/samples/taskbar-reordering.html';
  await p.goto(url);
  await p.waitForSelector('.win-bar-arrange');
  const order = () => p.evaluate(() => pudlWindows.state().taskbarOrder);
  const original = ['notes', 'files', 'terminal', 'search', 'help', 'settings', 'preview', 'output'];
  assert.deepEqual(await order(), original);
  const snapshot = await p.evaluate(() => { const s = pudlWindows.state(); return { open: s.open, top: s.top, recent: s.recent, place: s.place }; });
  await p.evaluate(() => { window.keptInput = document.querySelector('[data-win="notes"] input'); window.keptTab = document.querySelector('.win-bar [data-win-tab="notes"]'); });
  assert(await p.evaluate(() => pudlWindows.reorderTaskbar('output', { before: 'notes' })));
  assert.deepEqual(await order(), ['output', ...original.slice(0, -1)]);
  assert.equal(await p.evaluate(() => new URLSearchParams(location.search).get('tb.order')), 'output,notes,files,terminal,search,help,settings,preview');
  assert.deepEqual(await p.evaluate(() => { const s = pudlWindows.state(); return { open: s.open, top: s.top, recent: s.recent, place: s.place }; }), snapshot, 'reordering does not change window activation or placement');
  assert(await p.evaluate(() => keptInput === document.querySelector('[data-win="notes"] input') && keptTab === document.querySelector('.win-bar [data-win-tab="notes"]')), 'mounted content and taskbar links survive');
  assert.deepEqual(await p.locator('.mirror [data-win-tab]').evaluateAll(t => t.map(e => e.getAttribute('data-win-tab'))), await order());
  await p.goBack(); await p.waitForFunction(() => pudlWindows.state().taskbarOrder[0] === 'notes');
  await p.goForward(); await p.waitForFunction(() => pudlWindows.state().taskbarOrder[0] === 'output');
  await p.reload(); await p.waitForSelector('.win-bar-arrange'); assert.equal((await order())[0], 'output');
  const historyLength = await p.evaluate(() => history.length);
  assert.equal(await p.evaluate(() => pudlWindows.reorderTaskbar('output', { before: 'output' })), false);
  assert.equal(await p.evaluate(() => pudlWindows.reorderTaskbar('child', { edge: 'start' })), false);
  assert.equal(await p.evaluate(() => pudlWindows.reorderTaskbar('output', { before: 'files', after: 'notes' })), false);
  assert.equal(await p.evaluate(() => history.length), historyLength, 'invalid/no-op moves do not write history');
  await p.locator('.win-bar [data-win-tab="output"]').focus(); await p.keyboard.press('Alt+Shift+ArrowRight');
  assert.equal((await order())[1], 'output');
  assert.equal(await p.evaluate(() => document.activeElement.getAttribute('data-win-tab')), 'output');
  await p.evaluate(() => document.documentElement.dir = 'rtl');
  await p.keyboard.press('Alt+Shift+ArrowRight'); assert.equal((await order())[0], 'output', 'RTL mirrors physical arrows');
  await p.evaluate(() => document.documentElement.dir = 'ltr');
  await p.locator('.win-bar [data-win-tab="files"]').click({ button: 'right' });
  await p.getByRole('menuitem', { name: 'Taskbar order', exact: true }).click();
  await p.getByRole('menuitem', { name: 'Move to beginning', exact: true }).click();
  assert.equal((await order())[0], 'files');
  await p.locator('.win-bar-arrange').click();
  const dialog = p.getByRole('dialog', { name: 'Arrange taskbar', exact: true });
  await dialog.waitFor();
  await dialog.locator('select').selectOption('help');
  assert.equal(await dialog.locator('select').inputValue(), 'help', 'arranger selection stays on the chosen window');
  assert.equal(await dialog.getByRole('button', { name: 'Move to beginning', exact: true }).isEnabled(), true, 'selected window can move to the beginning');
  await dialog.getByRole('button', { name: 'Move to beginning', exact: true }).click();
  assert.equal((await order())[0], 'files', 'draft moves do not mutate committed state');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal((await order())[0], 'files');
  await p.locator('.win-bar-arrange').click(); await dialog.locator('select').selectOption('help');
  await dialog.getByRole('button', { name: 'Move to beginning', exact: true }).click();
  await dialog.getByRole('button', { name: 'Apply order', exact: true }).click();
  assert.equal((await order())[0], 'help', 'required windows can move in the taskbar');
  const beforeDrag = await order();
  const tab = p.locator('.win-bar [data-win-tab="help"]'), end = p.locator('.win-bar [data-win-tab="preview"]');
  const a = await tab.boundingBox(), z = await end.boundingBox();
  await p.mouse.move(a.x + a.width / 2, a.y + a.height / 2); await p.mouse.down();
  await p.mouse.move(z.x + z.width - 2, z.y + z.height / 2, { steps: 8 });
  await p.waitForSelector('.win-taskbar-marker'); await p.keyboard.press('Escape'); await p.mouse.up();
  assert.deepEqual(await order(), beforeDrag, 'Escape cancels without a reorder');
  await p.mouse.move(a.x + a.width / 2, a.y + a.height / 2); await p.mouse.down();
  await p.mouse.move(z.x + z.width - 2, z.y + z.height / 2, { steps: 8 }); await p.mouse.up();
  assert.notDeepEqual(await order(), beforeDrag, 'pointer drag commits');
  assert.equal(await p.evaluate(() => pudlWindows.state().top), snapshot.top, 'drag release does not activate the window');
  const afterDrag = await order();
  const firstVisible = p.locator('.win-bar [data-win-tab="files"]');
  const dragStart = await firstVisible.boundingBox(), dragEnd = await tab.boundingBox();
  await p.mouse.move(dragStart.x + dragStart.width / 2, dragStart.y + dragStart.height / 2); await p.mouse.down();
  await p.mouse.move(dragEnd.x + dragEnd.width - 2, dragEnd.y + dragEnd.height / 2, { steps: 4 });
  await p.waitForSelector('.win-taskbar-marker');
  await p.setViewportSize({ width: 1400, height: 900 }); await p.mouse.up();
  assert.deepEqual(await order(), afterDrag, 'viewport resize cancels a drag');
  assert.equal(await p.locator('.win-taskbar-marker').count(), 0);
  await p.setViewportSize({ width: 390, height: 900 });
  await p.waitForSelector('.win-bar-more:visible');
  await p.locator('.win-bar-more').click();
  await p.getByRole('menuitem', { name: 'Arrange taskbar', exact: true }).click(); await dialog.waitFor();
  assert.equal(await dialog.locator('option').count(), 8, 'arranger includes overflow entries');
  await p.screenshot({ path: out('taskbar-reorder-narrow.png') });
  assert.equal(await dialog.locator('[role="toolbar"]').count(), 1, 'arrangement actions use the shared toolbar');
  assert(await dialog.locator('[role="toolbar"]').evaluate(e => e.scrollWidth <= e.clientWidth + 1), 'toolbar fits the narrow popup');
  await dialog.locator('select').selectOption('help');
  await dialog.locator('[role="toolbar"]').evaluate(e => { e.style.width = '180px'; pudlToolbar.fit(e); });
  await dialog.getByRole('button', { name: 'Taskbar order', exact: true }).click();
  await p.getByRole('menuitem', { name: 'Move to beginning', exact: true }).click();
  assert(await dialog.isVisible(), 'folded move commands retain the arrangement draft');
  assert.equal(await dialog.locator('select').inputValue(), 'help');
  await dialog.locator('[role="toolbar"]').evaluate(e => { e.style.width = ''; pudlToolbar.fit(e); });
  await p.evaluate(() => pudlWindows.open('fresh')); await p.waitForFunction(() => pudlWindows.state().open.includes('fresh'));
  await p.evaluate(() => pudlWindows.close('preview')); await p.waitForFunction(() => !pudlWindows.state().open.includes('preview'));
  assert.equal(await dialog.locator('option[value="preview"]').count(), 0);
  assert.equal(await dialog.locator('option[value="fresh"]').count(), 1);
  await dialog.getByRole('button', { name: 'Apply order', exact: true }).click();
  assert(!(await order()).includes('preview'), 'applying a live draft cannot resurrect closed windows');
  await p.setViewportSize({ width: 1500, height: 900 });
  await p.locator('.win-bar-arrange').click(); await dialog.locator('select').selectOption('fresh');
  const freshIndex = (await order()).indexOf('fresh');
  assert(await p.evaluate(() => pudlWindows.rekey('fresh', 'renamed')));
  assert.equal((await order())[freshIndex], 'renamed', 'rekey preserves the taskbar slot');
  assert.equal(await dialog.locator('select').inputValue(), 'renamed', 'draft selection follows rekey');
  await p.evaluate(() => pudlWindows.replace('renamed', 'preview'));
  await p.waitForFunction(() => pudlWindows.state().open.includes('preview'));
  assert.equal((await order())[freshIndex], 'preview', 'replacement preserves the taskbar slot');
  assert.equal(await dialog.locator('select').inputValue(), 'preview', 'draft selection follows replacement');
  await dialog.getByRole('button', { name: 'Apply order', exact: true }).click();
  assert.equal((await order())[freshIndex], 'preview');
  assert(await p.evaluate(() => { const s = pudlWindows.state(); s.taskbarOrder.reverse(); return s.taskbarOrder.join() !== pudlWindows.state().taskbarOrder.join(); }), 'state order is detached');
  await p.locator('.win-bar-arrange').click(); await dialog.waitFor();
  const input = p.locator('[data-win="notes"] input');
  await input.focus(); await p.keyboard.press('Escape');
  await p.waitForFunction(() => !document.querySelector('.win-taskbar-arrangement'));
  assert(await input.evaluate(e => e === document.activeElement), 'closing a popover does not steal outside focus');
  await p.goto(url + '?open=notes,files,help&tb.order=files,files,missing'); await p.waitForSelector('.win-bar-arrange');
  assert.deepEqual(await order(), ['files', 'notes', 'help'], 'URL order discards duplicate and unknown keys and appends missing roots');
  await p.goto(url + '?no-reorder=1'); await p.waitForSelector('.win-bar [data-win-tab]');
  assert.equal(await p.locator('.win-bar-arrange').count(), 0, 'feature is opt-in');
  assert.equal(await p.evaluate(() => pudlWindows.reorderTaskbar('notes', { edge: 'end' })), false);
  await p.goto(url); await p.waitForSelector('.win-bar-arrange');
  await p.evaluate(() => {
    const bar = document.querySelector('.win-bar'); bar.style.top = '0'; bar.style.bottom = 'auto'; bar.setAttribute('data-win-bar-edge', 'top');
  });
  const topStart = await p.locator('.win-bar [data-win-tab="notes"]').boundingBox();
  const topEnd = await p.locator('.win-bar [data-win-tab="files"]').boundingBox();
  await p.mouse.move(topStart.x + topStart.width / 2, topStart.y + topStart.height / 2); await p.mouse.down();
  await p.mouse.move(topEnd.x + topEnd.width - 2, topEnd.y + topEnd.height / 2, { steps: 4 });
  await p.waitForSelector('.win-taskbar-marker[data-below]');
  assert(await p.locator('.win-taskbar-marker').evaluate(e => parseFloat(getComputedStyle(e, '::after').top) >= e.getBoundingClientRect().height), 'top-edge taskbar previews show their label below the strip');
  await p.keyboard.press('Escape'); await p.mouse.up();
  await p.evaluate(() => { const bar = document.querySelector('.win-bar'); bar.style.top = ''; bar.style.bottom = ''; bar.removeAttribute('data-win-bar-edge'); });
  await p.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' });
  await p.locator('.win-bar-arrange').click(); await dialog.waitFor();
  assert(await dialog.locator('select').isVisible(), 'arrangement remains available with forced colours and reduced motion');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await p.emulateMedia({ forcedColors: 'none' });
  await p.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await p.locator('.win-bar-arrange').click(); await dialog.waitFor();
  await p.screenshot({ path: out('taskbar-reorder-dark.png') });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  const touch = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true });
  await touch.goto(url); await touch.waitForSelector('.win-bar-arrange');
  const touchDialog = touch.getByRole('dialog', { name: 'Arrange taskbar', exact: true });
  if (await touch.evaluate(() => navigator.maxTouchPoints > 0)) await touch.locator('.win-bar-arrange').tap();
  else await touch.locator('.win-bar-arrange').click();
  await touchDialog.locator('select').selectOption('help');
  await touchDialog.getByRole('button', { name: 'Move to beginning', exact: true }).click();
  await touchDialog.getByRole('button', { name: 'Apply order', exact: true }).click();
  assert.equal(await touch.evaluate(() => pudlWindows.state().taskbarOrder[0]), 'help', 'narrow touch arrangement needs no drag');
  await touch.close();
  assert.deepEqual(errors, []);
  await b.close(); console.log('PASS taskbar reordering');
})().catch(e => { console.error('FAIL ' + e.stack.split('\n').filter(l => l.includes('.test.js:')).join(' ') + ' ' + e.message.slice(-300).replace(/\n/g, ' ')); process.exit(1); });
