const { launch, ROOT, engine } = require('./lib');
const assert = require('assert/strict');
(async () => {
  const browser = await launch();
  const p = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await p.goto(ROOT + '/samples/menu-ribbon.html');
  await p.waitForFunction(() => window.pudlMenubar && document.querySelector('.menubar-title'));
  await p.evaluate(() => pudlMenubar.ribbon(true));
  const tab = p.locator('.menubar-title[role="tab"]').filter({ hasText: 'View' }).first();
  await tab.waitFor();
  await p.evaluate(() => document.querySelector('.menubar-row').classList.add('menubar-title-glyphs'));
  assert.equal(await tab.getAttribute('data-tooltip'), 'View');
  assert.equal(await tab.getAttribute('aria-label'), 'View');
  await tab.hover();
  await p.waitForSelector('.tooltip:popover-open');
  assert.equal(await p.locator('.tooltip').innerText(), 'View');
  await p.keyboard.press('Escape');
  await p.mouse.move(1400, 880);
  await p.keyboard.press('Tab');
  await tab.focus();
  await p.waitForSelector('.tooltip:popover-open');
  assert.equal(await p.locator('.tooltip').innerText(), 'View');
  await p.keyboard.press('Escape');
  const chooser = p.getByRole('button', { name: 'Ribbon tabs', exact: true });
  await chooser.focus();
  await p.keyboard.press('ArrowDown');
  const menu = p.locator('.context-menu:popover-open');
  await menu.waitFor();
  assert.equal(await chooser.getAttribute('aria-expanded'), 'true');
  assert.ok(await menu.getByRole('menuitemradio', { name: 'View', exact: true }).isVisible());
  await menu.getByRole('menuitemradio', { name: 'View', exact: true }).click();
  await p.waitForFunction(() => document.querySelector('.menubar-title[aria-selected="true"]').textContent.trim() === 'View');
  await chooser.click();
  assert.equal(await menu.getByRole('menuitemradio', { name: 'View', exact: true }).getAttribute('aria-checked'), 'true');
  await p.keyboard.press('Escape');
  await p.waitForFunction(() => document.querySelector('.menubar-ribbon-tabs').getAttribute('aria-expanded') === 'false');
  assert.equal(await chooser.evaluate(e => e === document.activeElement), true);
  await p.goto(ROOT + '/tests/fixtures/command-bar.html');
  await p.waitForSelector('.ribbon-ready');
  assert.equal(await p.locator('#tab-insert').getAttribute('data-tooltip'), 'Insert');
  await p.locator('.ribbon-tabs').click();
  await p.getByRole('menuitemradio', { name: 'Insert', exact: true }).click();
  assert.equal(await p.locator('#tab-insert').getAttribute('aria-selected'), 'true');
  const touch = await browser.newContext({ viewport: { width: 1440, height: 900 }, hasTouch: true });
  const phone = await touch.newPage();
  await phone.goto(ROOT + '/samples/menu-ribbon.html');
  await phone.waitForFunction(() => window.pudlMenubar && document.querySelector('.menubar-title'));
  await phone.evaluate(() => pudlMenubar.ribbon(true));
  const activate = locator => engine === 'firefox' ? locator.click() : locator.tap();
  await activate(phone.locator('.menubar-ribbon-tabs'));
  await activate(phone.locator('.context-menu:popover-open').getByRole('menuitemradio', { name: 'View', exact: true }));
  assert.equal(await phone.locator('.menubar-title[aria-selected="true"]').innerText(), 'View');
  await touch.close();
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
