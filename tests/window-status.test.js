const { launch, ROOT, out } = require('./lib');
const assert = require('assert/strict');
(async () => {
  const browser = await launch();
  const p = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  await p.goto(ROOT + '/tests/fixtures/window-status.html');
  await p.waitForFunction(() => window.pudlWindows && document.querySelector('.win-status-toggle'));
  const win = p.locator('[data-win="status"]');
  const compact = () => win.locator('.win-statuses').getAttribute('data-win-status-compact');
  await win.locator('input').click();
  for (const theme of ['light', 'dark']) {
    await p.evaluate(t => document.documentElement.dataset.theme = t, theme);
    assert(await win.evaluate(w => {
      const title = getComputedStyle(w.querySelector('.win-title'));
      return [...w.querySelectorAll('.win-status')].every(s => { const c = getComputedStyle(s); return c.color === title.color && c.backgroundColor === 'rgba(0, 0, 0, 0)' && c.borderTopColor === c.color && c.boxShadow === 'none'; });
    }), 'status follows the active title palette in ' + theme);
    assert.equal(await compact(), null, 'wide title bar keeps statuses visible');
    await p.screenshot({ path: out('window-status-' + theme + '.png') });
  }
  await p.emulateMedia({ forcedColors: 'active' });
  assert(await win.evaluate(w => getComputedStyle(w.querySelector('.win-status')).color === getComputedStyle(w.querySelector('.win-title')).color), 'forced colours follow the title');
  await p.emulateMedia({ forcedColors: 'none' });
  await p.locator('[data-win="plain"] .win-head').click();
  assert(await win.evaluate(w => getComputedStyle(w.querySelector('.win-status')).color === getComputedStyle(w.querySelector('.win-title')).color), 'inactive statuses retain title contrast');
  await win.locator('input').click();
  await p.evaluate(() => document.documentElement.dir = 'rtl');
  await win.evaluate(w => w.style.setProperty('--win-w', '.27'));
  await p.waitForFunction(() => document.querySelector('.win-statuses').hasAttribute('data-win-status-compact'));
  assert(await win.locator('.win-title').evaluate(t => t.scrollWidth <= t.clientWidth + 1), 'statuses yield before the title truncates');
  await win.locator('.win-status-toggle').click();
  await p.waitForSelector('.win-status-popover:popover-open');
  assert.deepEqual(await p.locator('.win-status-popover li').allTextContents(), ['Working', 'Background 2', 'Subagents 3']);
  await win.locator('.win-status').nth(1).evaluate(s => s.textContent = 'Background 4');
  await p.waitForFunction(() => document.querySelector('.win-status-popover').textContent.includes('Background 4'));
  await p.keyboard.press('Escape');
  await p.waitForFunction(() => !document.querySelector('.win-status-popover').matches(':popover-open'));
  await win.locator('.win-status-toggle').focus(); await p.keyboard.press('Enter');
  await p.waitForSelector('.win-status-popover:popover-open');
  await win.evaluate(w => w.style.setProperty('--win-w', '.8'));
  await p.waitForFunction(() => !document.querySelector('.win-statuses').hasAttribute('data-win-status-compact'));
  assert.equal(await p.locator('.win-status-popover:popover-open').count(), 0, 'widening closes the compact popup');
  assert(await win.locator('.win-head').evaluate(h => document.activeElement === h), 'widening returns focus to the header');
  await p.evaluate(() => pudlWindows.retitle('status', 'A much longer conversation title '.repeat(8)));
  await p.waitForFunction(() => document.querySelector('.win-statuses').hasAttribute('data-win-status-compact'));
  await p.evaluate(() => pudlWindows.retitle('status', 'Agent'));
  await p.waitForFunction(() => !document.querySelector('.win-statuses').hasAttribute('data-win-status-compact'));
  await win.locator('[data-win-action="menu"]').click();
  await p.waitForSelector('#win-menu-status:popover-open');
  await win.locator('.win-status').first().evaluate(s => s.hidden = true);
  await win.locator('.win-status').nth(1).evaluate(s => s.hidden = true);
  await win.locator('.win-status').nth(2).evaluate(s => s.hidden = true);
  await p.waitForFunction(() => document.querySelector('.win-statuses').hidden);
  assert.equal(await p.evaluate(() => pudlWindows.menuCommands('status').some(c => c.id === 'status')), false, 'empty statuses have no menu command');
  await p.locator('#win-menu-status [data-win-cmd="status"]').click();
  assert.equal(await p.locator('.win-status-popover:popover-open').count(), 0, 'a stale menu command cannot open an empty status popup');
  await win.locator('.win-status').first().evaluate(s => s.hidden = false);
  await p.waitForFunction(() => !document.querySelector('.win-statuses').hidden);
  await p.evaluate(() => document.documentElement.dir = 'ltr');
  await p.evaluate(() => pudlWindows.dock('status', 'left'));
  await p.waitForFunction(() => document.querySelector('[data-win="status"]').hasAttribute('data-win-edge'));
  await win.locator('[data-win-action=minimize]').click();
  await p.waitForFunction(() => document.querySelector('[data-win="status"]').classList.contains('win-collapsed'));
  await p.waitForFunction(() => document.querySelector('.win-statuses').hasAttribute('data-win-status-compact'));
  assert.notEqual(await compact(), null, 'vertical title bars use the compact status control');
  await win.locator('.win-status-toggle').click();
  await p.waitForSelector('.win-status-popover:popover-open');
  await p.keyboard.press('Escape');
  await p.goto(ROOT + '/tests/fixtures/window-status.html?shared=1');
  await p.waitForFunction(() => window.pudlWindows && document.querySelector('.win-status-toggle'));
  await p.evaluate(() => pudlWindows.dock('status', 'left'));
  await p.waitForFunction(() => !document.querySelector('[data-win="status"] .win-head').getClientRects().length);
  await p.locator('[data-dock-key="status"]').click({ button: 'right' });
  await p.locator('.context-menu:popover-open').getByRole('menuitem', { name: 'Window status', exact: true }).click();
  await p.waitForSelector('.win-status-popover:popover-open');
  assert.equal(await p.locator('.win-status-popover li').count(), 3, 'shared dock window commands retain full status access');
  await p.keyboard.press('Escape');
  assert(await p.locator('[data-dock-key="status"]').evaluate(t => document.activeElement === t), 'shared dock status dismissal returns focus to its tab');
  await p.evaluate(() => pudlWindows.dockMode('left', 'rail'));
  await p.locator('[data-dock-key="status"]').click({ button: 'right' });
  await p.locator('.context-menu:popover-open').getByRole('menuitem', { name: 'Window status', exact: true }).click();
  await p.waitForSelector('.win-status-popover:popover-open');
  assert(await p.locator('.win-status-popover').isVisible(), 'collapsed dock rails retain visible status access');
  await p.keyboard.press('Escape');
  await p.evaluate(() => pudlWindows.close('status'));
  await p.waitForFunction(() => !document.querySelector('[data-win="status"]'));
  assert.equal(await p.locator('.win-status-popover').count(), 0, 'closing releases the generated popup');
  assert.deepEqual(errors, []);
  await browser.close(); console.log('PASS title-bar statuses');
})().catch(e => { console.error('FAIL ' + e.stack.replace(/\n/g, ' ')); process.exit(1); });
