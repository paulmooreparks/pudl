"""Rebuild committed Inter subsets; --check verifies them without writing.

Install build/fonts-requirements.txt first. Consumers need no Python tooling.
The full fonts remain in dist/fonts as source and for existing direct links.
See https://fonttools.readthedocs.io/en/latest/subset/index.html.
"""
import argparse
import io
import unicodedata
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "dist/fonts"
START = "/* BEGIN INTER: generated by build/fonts.py. */"
END = "/* END INTER */"
# Script ranges from issue #11, with all U+2190-21FF arrows in Latin.
# Latin is declared last so shared punctuation uses the common subset.
RANGES = {
    "cyrillic-ext": "0460-052F,1C80-1C8A,20B4,2DE0-2DFF,A640-A69F,FE2E-FE2F",
    "cyrillic": "0301,0400-045F,0490-0491,04B0-04B1,2116",
    "greek-ext": "1F00-1FFF",
    "greek": "0370-0377,037A-037F,0384-038A,038C,038E-03A1,03A3-03FF",
    "vietnamese": "0102-0103,0110-0111,0128-0129,0168-0169,01A0-01A1,01AF-01B0,0300-0301,0303-0304,0308-0309,0323,0329,1EA0-1EF9,20AB",
    "latin-ext": "0100-02BA,02BD-02C5,02C7-02CC,02CE-02D7,02DD-02FF,0304,0308,0329,1D00-1DBF,1E00-1E9F,1EF2-1EFF,2020,20A0-20AB,20AD-20C0,2113,2C60-2C7F,A720-A7FF",
    "latin": "0000-00FF,0131,0152-0153,02BB-02BC,02C6,02DA,02DC,0304,0308,0329,2000-206F,20AC,2122,2190-21FF,2212,2215,FEFF,FFFD",
}


def codepoints(ranges):
    result = set()
    for item in ranges.split(","):
        ends = [int(x, 16) for x in item.split("-")]
        result.update(range(ends[0], ends[-1] + 1))
    return result


def unicode_range(points):
    runs = []
    for point in sorted(points):
        if runs and runs[-1][1] + 1 == point:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ", ".join(f"U+{a:04X}" + (f"-{b:04X}" if a != b else "") for a, b in runs)


def axes(font):
    return [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in font["fvar"].axes]


def features(font, table):
    return {r.FeatureTag for r in font[table].table.FeatureList.FeatureRecord}


def generate():
    outputs = {}
    css = [START, "/* Inter by Rasmus Andersson, SIL OFL 1.1 (fonts/Inter-LICENSE.txt).",
           "   Script subsets retain weight, optical size, and OpenType features. */"]
    for style, source, prefix in [("normal", "InterVariable.woff2", "Inter"),
                                  ("italic", "InterVariable-Italic.woff2", "Inter-Italic")]:
        original = TTFont(FONTS / source, recalcTimestamp=False)
        covered = set(original.getBestCmap())
        groups = {name: codepoints(ranges) & covered for name, ranges in RANGES.items()}
        groups = {"rest": covered - set.union(*groups.values()), **groups}
        # CSS cluster matching needs a base and its combining marks in one face.
        # Keep source-supported marks with each script, including decomposed text.
        marks = {cp for cp in covered if unicodedata.category(chr(cp)).startswith("M")}
        groups = {name: points | marks for name, points in groups.items()}
        retained = set()
        kept_features = {table: set() for table in ("GSUB", "GPOS")}
        for name, points in groups.items():
            assert points, f"Empty subset: {style}/{name}"
            # Auto-hinters derive alignment zones from representative letters.
            # Keep basic alphabets inside the file without advertising them in
            # this face's CSS range. See docs/FONTS.md for the FreeType contract.
            context = codepoints("0020-007E")
            if name.startswith("greek"):
                context |= codepoints(RANGES["greek"])
            if name.startswith("cyrillic"):
                context |= codepoints(RANGES["cyrillic"])
            file_points = points | (context & covered)
            font = TTFont(FONTS / source, recalcTimestamp=False, recalcBBoxes=False)
            options = subset.Options()
            options.layout_features = ["*"]
            options.name_IDs = ["*"]
            options.name_languages = ["*"]
            options.notdef_outline = True
            options.glyph_names = True
            options.recalc_timestamp = False
            options.harfbuzz_repacker = False
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=file_points)
            worker.subset(font)
            data = io.BytesIO()
            font.flavor = "woff2"
            font.save(data)
            # Verify serialized files, not just the subsetter's in-memory result.
            result = TTFont(io.BytesIO(data.getvalue()))
            assert set(result.getBestCmap()) == file_points, f"Coverage: {style}/{name}"
            assert axes(result) == axes(original), f"Variable axes: {style}/{name}"
            assert result["post"].formatType == original["post"].formatType
            for table in kept_features:
                kept_features[table].update(features(result, table))
            retained.update(points)
            filename = f"{prefix}-{name}.woff2"
            outputs[FONTS / filename] = data.getvalue()
            css.extend(["@font-face {", '  font-family: "Inter";',
                        f"  font-style: {style};", "  font-weight: 100 900;",
                        "  font-display: swap;",
                        f'  src: url("fonts/{filename}") format("woff2");',
                        f"  unicode-range: {unicode_range(points)};", "}"])
        assert retained == covered, f"Missing characters in {style}"
        for table in kept_features:
            assert kept_features[table] == features(original, table), f"Lost {table} features"
    css.append(END)
    stylesheet = ROOT / "dist/pudl.css"
    text = stylesheet.read_text(encoding="utf-8")
    before, tail = text.split(START, 1)
    _, after = tail.split(END, 1)
    outputs[stylesheet] = (before + "\n".join(css) + after).encode("utf-8")
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in generate().items():
        if args.check:
            actual = path.read_bytes()
            if path.suffix == ".css":
                actual = actual.replace(b"\r\n", b"\n")
            if actual != data:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)
        print(f"{'Checked' if args.check else 'Wrote'} {path.relative_to(ROOT)} ({len(data):,} bytes)")
