"""Rebuild committed Inter subsets; --check verifies them without writing.

Install build/fonts-requirements.txt first. Consumers need no Python tooling.
The full fonts remain in dist/fonts as source and for existing direct links.
See https://fonttools.readthedocs.io/en/latest/subset/index.html and
https://fonttools.readthedocs.io/en/latest/varLib/instancer.html.

Two sets are built from the same script ranges. The default set, which
pudl.css declares as "Inter", keeps the weights from 400 to 900, the optical
size of text (14, the font's default) and the OpenType features in
LEAN_FEATURES. The full set, which pudl-fonts-full.css declares as
"Inter Full", keeps every weight, the optical-size axis and every feature,
as PUDL shipped before 0.70.0.
"""
import argparse
import io
import unicodedata
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "dist/fonts"
START = "/* BEGIN INTER: generated by build/fonts.py. */"
END = "/* END INTER */"
FALLBACK = 'system-ui, -apple-system, "Segoe UI", "Roboto", sans-serif'
# The features a browser applies by itself, the ones PUDL asks for
# (tabular numerals) and the numeric and case forms CSS can ask for by name
# (font-variant-numeric, -position, -caps). Character variants and stylistic
# sets need the full set.
LEAN_FEATURES = ["ccmp", "locl", "rvrn", "calt", "kern", "mark", "mkmk",
                 "tnum", "pnum", "zero", "frac", "numr", "dnom", "sups",
                 "subs", "case"]
SETS = [
    # Weights stop at 400 and 900, where the font has masters of its own.
    # Stopping at 700, which is not one, made the instancer re-express the
    # weights between, moving some advances by a unit and points by up to
    # 1.1 units; 900 costs about 4 KB in Latin and keeps every advance exact.
    {"family": "Inter", "prefix": "Inter", "weight": "400 900",
     "limits": {"wght": (400, 400, 900), "opsz": 14}, "features": LEAN_FEATURES,
     "note": "Script subsets keep weights 400 to 900, the optical size of text, and\n"
             "   the OpenType features CSS asks for by name; pudl-fonts-full.css has the rest."},
    {"family": "Inter Full", "prefix": "Inter-Full", "weight": "100 900",
     "limits": None, "features": ["*"],
     "note": "Script subsets retain weight, optical size, and OpenType features."},
]
# Script ranges from issue #11, with all U+2190-21FF arrows in Latin.
# Latin is declared last so shared punctuation uses the common subset.
RANGES = {
    "cyrillic-ext": "0460-052F,1C80-1C8A,20B4,2DE0-2DFF,A640-A69F,FE2E-FE2F",
    "cyrillic": "0301,0400-045F,0490-0491,04B0-04B1,2116",
    "greek-ext": "1F00-1FFF",
    "greek": "0370-0377,037A-037F,0384-038A,038C,038E-03A1,03A3-03FF",
    "vietnamese": "0102-0103,0110-0111,0128-0129,0168-0169,01A0-01A1,01AF-01B0,0300-0301,0303-0304,0308-0309,0323,0329,1EA0-1EF9,20AB",
    "latin-ext": "0100-02BA,02BD-02C5,02C7-02CC,02CE-02D7,02DD-02FF,0304,0308,0329,1D00-1DBF,1E00-1E9F,1EF2-1EFF,2020,20A0-20AB,20AD-20C0,2113,2C60-2C7F,A720-A7FF",
    "latin": "0000-00FF,0131,0152-0153,02BB-02BC,02C6,02DA,02DC,0304,0308,0329,2000-206F,20AC,2122,2190-21FF,2212,2215,FEFF,FFFD",
}


def codepoints(ranges):
    result = set()
    for item in ranges.split(","):
        ends = [int(x, 16) for x in item.split("-")]
        result.update(range(ends[0], ends[-1] + 1))
    return result


def unicode_range(points):
    runs = []
    for point in sorted(points):
        if runs and runs[-1][1] + 1 == point:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ", ".join(f"U+{a:04X}" + (f"-{b:04X}" if a != b else "") for a, b in runs)


def axes(font):
    return [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in font["fvar"].axes]


def features(font, table):
    return {r.FeatureTag for r in font[table].table.FeatureList.FeatureRecord}


def expected_axes(original, limits):
    result = []
    for tag, low, default, high in axes(original):
        limit = (limits or {}).get(tag)
        if limit is None:
            result.append((tag, low, default, high))
        elif isinstance(limit, tuple):
            result.append((tag, limit[0], limit[1], limit[2]))
    return result


# Weights at which a lean subset must draw every glyph as the whole font
# does at the optical size of text: both ends of PUDL's range and one
# between them, where interpolation shows. Advances must be exact. A
# variable font stores its changes in whole font units, so pinning the
# optical size re-expresses some of them and may move a point of an outline
# by a fraction of a unit (0.27 at most in 0.70.0); it must stay within
# OUTLINE_UNITS.
CHECK_WEIGHTS = (400, 600, 700)
OUTLINE_UNITS = 0.5
_whole = {}


def whole_instance(source, weight):
    key = (source, weight)
    if key not in _whole:
        font = TTFont(FONTS / source, lazy=False)
        _whole[key] = instancer.instantiateVariableFont(font, {"wght": weight, "opsz": 14})
    return _whole[key]


def same_drawing(lean, source, label):
    """Every glyph's advance and outline, at each of CHECK_WEIGHTS, against
    the whole font instanced at the same weight. A browser measures text
    after its rasterizer has drawn it, and Linux Chromium, which fits
    outlines to pixels, draws some Greek text at weight 600 a pixel narrower
    from any subset, the full set included, than from the whole font; the
    font data is what this proves equal."""
    data = io.BytesIO()
    lean.save(data)
    for weight in CHECK_WEIGHTS:
        mine = instancer.instantiateVariableFont(TTFont(io.BytesIO(data.getvalue()), lazy=False), {"wght": weight})
        theirs = whole_instance(source, weight)
        for glyph in mine.getGlyphOrder():
            assert mine["hmtx"][glyph][0] == theirs["hmtx"][glyph][0], f"Advance of {glyph} at {weight}: {label}"
            a, b = mine["glyf"][glyph], theirs["glyf"][glyph]
            ca = list(a.getCoordinates(mine["glyf"])[0]) if a.numberOfContours else []
            cb = list(b.getCoordinates(theirs["glyf"])[0]) if b.numberOfContours else []
            assert len(ca) == len(cb), f"Outline of {glyph}: {label}"
            for (x1, y1), (x2, y2) in zip(ca, cb):
                assert abs(x1 - x2) <= OUTLINE_UNITS and abs(y1 - y2) <= OUTLINE_UNITS, f"Outline of {glyph} at {weight}: {label}"


def generate():
    outputs = {}
    for spec in SETS:
        outputs.update(generate_set(spec))
    return outputs


def generate_set(spec):
    outputs = {}
    css = [START, "/* Inter by Rasmus Andersson, SIL OFL 1.1 (fonts/Inter-LICENSE.txt).",
           "   " + spec["note"] + " */"]
    for style, source, prefix in [("normal", "InterVariable.woff2", spec["prefix"]),
                                  ("italic", "InterVariable-Italic.woff2", spec["prefix"] + "-Italic")]:
        original = TTFont(FONTS / source, recalcTimestamp=False)
        covered = set(original.getBestCmap())
        groups = {name: codepoints(ranges) & covered for name, ranges in RANGES.items()}
        groups = {"rest": covered - set.union(*groups.values()), **groups}
        # CSS cluster matching needs a base and its combining marks in one face.
        # Keep source-supported marks with each script, including decomposed text.
        marks = {cp for cp in covered if unicodedata.category(chr(cp)).startswith("M")}
        groups = {name: points | marks for name, points in groups.items()}
        retained = set()
        kept_features = {table: set() for table in ("GSUB", "GPOS")}
        for name, points in groups.items():
            assert points, f"Empty subset: {style}/{name}"
            # Auto-hinters derive alignment zones from representative letters.
            # Keep basic alphabets inside the file without advertising them in
            # this face's CSS range. See docs/FONTS.md for the FreeType contract.
            context = codepoints("0020-007E")
            if name.startswith("greek"):
                context |= codepoints(RANGES["greek"])
            if name.startswith("cyrillic"):
                context |= codepoints(RANGES["cyrillic"])
            file_points = points | (context & covered)
            font = TTFont(FONTS / source, recalcTimestamp=False, recalcBBoxes=False, lazy=False)
            options = subset.Options()
            options.layout_features = spec["features"]
            options.name_IDs = ["*"]
            options.name_languages = ["*"]
            options.notdef_outline = True
            options.glyph_names = True
            options.recalc_timestamp = False
            options.harfbuzz_repacker = False
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=file_points)
            worker.subset(font)
            if spec["limits"]:
                # Subset first, so the instancer works on the glyphs kept.
                font = instancer.instantiateVariableFont(font, spec["limits"])
            data = io.BytesIO()
            font.flavor = "woff2"
            font.save(data)
            # Verify serialized files, not just the subsetter's in-memory result.
            result = TTFont(io.BytesIO(data.getvalue()))
            assert set(result.getBestCmap()) == file_points, f"Coverage: {style}/{name}"
            assert axes(result) == expected_axes(original, spec["limits"]), f"Variable axes: {style}/{name}"
            assert result["post"].formatType == original["post"].formatType
            if spec["limits"]:
                same_drawing(result, source, f"{style}/{name}")
            for table in kept_features:
                kept_features[table].update(features(result, table))
            retained.update(points)
            filename = f"{prefix}-{name}.woff2"
            outputs[FONTS / filename] = data.getvalue()
            css.extend(["@font-face {", f'  font-family: "{spec["family"]}";',
                        f"  font-style: {style};", f"  font-weight: {spec['weight']};",
                        "  font-display: swap;",
                        f'  src: url("fonts/{filename}") format("woff2");',
                        f"  unicode-range: {unicode_range(points)};", "}"])
        assert retained == covered, f"Missing characters in {style}"
        for table in kept_features:
            wanted = features(original, table)
            if spec["features"] != ["*"]:
                wanted &= set(spec["features"])
            assert kept_features[table] == wanted, f"Lost {table} features"
    css.append(END)
    if spec["family"] == "Inter":
        stylesheet = ROOT / "dist/pudl.css"
        text = stylesheet.read_text(encoding="utf-8")
        before, tail = text.split(START, 1)
        _, after = tail.split(END, 1)
        outputs[stylesheet] = (before + "\n".join(css) + after).encode("utf-8")
    else:
        stylesheet = ROOT / "dist/pudl-fonts-full.css"
        head = ["/* PUDL's text in the whole of Inter: every weight from 100 to 900, the",
                "   optical-size axis that tightens headings, and every OpenType feature,",
                "   such as the character variants and stylistic sets, as PUDL shipped",
                "   before 0.70.0. Load it after pudl.css and before a theme. It declares",
                '   the family "Inter Full" and makes it the text face; pudl.css\'s leaner',
                '   "Inter" is then never requested. Generated by build/fonts.py. */', ""]
        tail = ["", ":root {", f'  --font: "Inter Full", {FALLBACK};', "}", ""]
        outputs[stylesheet] = "\n".join(head + css + tail).encode("utf-8")
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in generate().items():
        if args.check:
            actual = path.read_bytes()
            if path.suffix == ".css":
                actual = actual.replace(b"\r\n", b"\n")
            if actual != data:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)
        print(f"{'Checked' if args.check else 'Wrote'} {path.relative_to(ROOT)} ({len(data):,} bytes)")
