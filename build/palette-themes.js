/* Companion palettes are independent of skin geometry and light/dark mode. */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const ids = ['bevel', 'gel', 'glaze'];
function base(form) {
  const file = JSON.parse(fs.readFileSync(path.join(root, 'vendor/pudl-spec/tokens/palette.' + form + '.tokens.json'), 'utf8'));
  return Object.fromEntries(Object.entries(file).filter(([k]) => !k.startsWith('$')).flatMap(([, group]) => Object.entries(group).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, v.$value.hex || v.$value])));
}
function rgb(hex) { return hex.slice(1).match(/../g).map(v => parseInt(v, 16)); }
function luminance(hex) { return rgb(hex).map(v => { v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }).reduce((sum, v, i) => sum + v * [.2126, .7152, .0722][i], 0); }
function contrast(a, b) { const x = luminance(a), y = luminance(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); }
function mix(a, b, amount) { const x = rgb(a), y = rgb(b); return '#' + x.map((v, i) => Math.round(v * amount + y[i] * (1 - amount)).toString(16).padStart(2, '0')).join(''); }
function adjusted(hex, surfaces, minimum, dark) {
  const source = rgb(hex), target = dark ? 255 : 0;
  for (let step = 0; step <= 100; step++) {
    const value = '#' + source.map(v => Math.round(v + (target - v) * step / 100).toString(16).padStart(2, '0')).join('');
    if (surfaces.every(bg => contrast(value, bg) >= minimum)) return value;
  }
  throw new Error('Palette cannot meet contrast');
}
function palette(id, form) {
  const definition = JSON.parse(fs.readFileSync(path.join(root, 'themes', id + '.json'), 'utf8'));
  const values = Object.assign(base(form), definition[form]);
  const surfaces = [values.bg, values.surface, values['surface-alt'], mix(values.light, values.surface, values.lit), mix(values.shade, values['surface-alt'], values.depth * .35)];
  /* Retain category families and syntax hues while accommodating warmer or
     cooler reading surfaces. Every generated value remains opaque. */
  for (const key of Object.keys(values)) {
    if (key.startsWith('category-')) values[key] = adjusted(values[key], [surfaces[0], surfaces[1], surfaces[3]], 3, form === 'dark');
    if (key.startsWith('syntax-') || key === 'text-muted') values[key] = adjusted(values[key], surfaces, 4.5, form === 'dark');
    if (['warn', 'danger', 'danger-hover', 'positive'].includes(key)) values[key] = adjusted(values[key], surfaces, 3, form === 'dark');
  }
  return values;
}
function compile(id) {
  let css = '/* Generated by build/palette-themes.js. Select with data-palette="' + id + '". */\n@media screen and (forced-colors: none) {\n';
  for (const form of ['light', 'dark']) {
    const condition = form === 'dark' ? '[data-theme="dark"]' : ':not([data-theme="dark"])';
    css += ':root:where([data-palette="' + id + '"]' + condition + ') {\n';
    for (const [key, value] of Object.entries(palette(id, form))) css += '  --' + (key === 'positive' ? 'pr' : key) + ': ' + (typeof value === 'number' ? value * 100 + '%' : value) + ';\n';
    css += '}\n';
  }
  return css + '}\n';
}
if (require.main === module) {
  for (const id of ids) {
    const file = path.join(root, 'dist', 'pudl-theme-' + id + '.css'), css = compile(id);
    if (process.argv.includes('--check')) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== css) throw new Error(file + ' is stale'); }
    else fs.writeFileSync(file, css);
  }
  console.log('Companion palette themes ' + (process.argv.includes('--check') ? 'checked' : 'generated'));
}
module.exports = { ids, palette, compile, contrast };
