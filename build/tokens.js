/* Writes the token block of dist/pudl.css from the PUDL specification's
   tokens, the one build step this repository has. The specification's
   token files and glyphs are vendored in vendor/pudl-spec/ at a tagged
   version, as adopters vendor this repository, and are never edited here:
   a change to a token is a change to pudl-spec, copied in by a release.

     node build/tokens.js           rewrites the block
     node build/tokens.js --check   fails if the block is not what the
                                    tokens produce, for the test suite

   The block runs from the BEGIN marker to the END marker. Everything else
   in pudl.css is written by hand. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SPEC = path.join(ROOT, 'vendor', 'pudl-spec');
const CSS = path.join(ROOT, 'dist', 'pudl.css');
const BEGIN = '/* BEGIN TOKENS: generated by build/tokens.js from vendor/pudl-spec. Edit the specification\'s tokens, not this block. */';
const END = '/* END TOKENS */';

/* The web keeps one older name: --pr, which a theme written before 0.20
   may still set, reaches --positive. */
const LEGACY = { positive: 'pr' };

function read(name) { return JSON.parse(fs.readFileSync(path.join(SPEC, 'tokens', name), 'utf8')); }

/* A comment of prose, wrapped to the width of the stylesheet, under a
   heading line when it is given one. */
function comment(text, indent, heading) {
  const pad = ' '.repeat(indent);
  const lines = [];
  let line = pad + '/*';
  if (heading) {
    const top = pad + '/* === ' + heading + ' ';
    lines.push(top + '='.repeat(Math.max(3, 78 - top.length)));
    line = pad + '  ';
  }
  text.split(/\s+/).forEach(w => {
    if (line.length + 1 + w.length > 76 && line.trim() !== '/*' && line.trim() !== '') { lines.push(line); line = pad + '  '; }
    line += ' ' + w;
  });
  lines.push(line + ' */');
  return lines.join('\n');
}

/* The groups and tokens of a token file, in order. A key starting with $
   is a property of the group, not a member. */
function groups(file) {
  return Object.keys(file).filter(k => k[0] !== '$').map(g => ({
    description: file[g].$description,
    type: file[g].$type,
    tokens: Object.keys(file[g]).filter(k => k[0] !== '$').map(k => ({ name: k, token: file[g][k] }))
  }));
}

function pct(n) { return String(Math.round(n * 1000) / 10) + '%'; }
function px(n) { return n === 0 ? '0' : n + 'px'; }

/* A named face is quoted, and CSS's own keywords for the system's faces
   are not, since quoting one would name a face called that. */
const GENERIC = ['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-serif', 'ui-sans-serif',
               'ui-monospace', 'ui-rounded', 'math', 'emoji', 'fangsong', '-apple-system'];
function family(v) {
  return (Array.isArray(v) ? v : [v]).map(f => GENERIC.indexOf(f) >= 0 ? f : '"' + f + '"').join(', ');
}

/* A token's value as CSS. */
function value(token, type) {
  const v = token.$value;
  const t = token.$type || type;
  if (typeof v === 'string' && /^\{.+\}$/.test(v)) return 'var(--' + v.slice(1, -1).split('.').pop() + ')';
  if (t === 'color') return v.hex;
  if (t === 'number') return pct(v);
  if (t === 'dimension') return v.value + v.unit;
  if (t === 'fontFamily') return family(v);
  throw new Error('no CSS for a token of type ' + t);
}

/* === The formulas of derived.json ====================================== */

function amount(a) {
  if (typeof a === 'number') return pct(a);
  if (typeof a === 'string') return 'var(--' + a + ')';
  return 'calc(var(--' + a.token + ') * ' + a.times + ')';
}

function colour(c) {
  if (typeof c === 'string') return c[0] === '#' || c === 'transparent' ? c : 'var(--' + c + ')';
  if (c.mix) return 'color-mix(in srgb, ' + colour(c.mix[0]) + ' ' + amount(c.by) + ', ' + colour(c.mix[1]) + ')';
  if (c.fade) return 'color-mix(in srgb, ' + colour(c.fade) + ' ' + amount(c.by) + ', transparent)';
  if (c.srgb) return 'rgb(' + c.srgb.map(n => Math.round(n * 255)).join(' ') + ' / ' + c.alpha + ')';
  throw new Error('not a colour: ' + JSON.stringify(c));
}

/* Values that run long are set on lines of their own, as the hand-written
   stylesheet set them. */
function formula(f) {
  if (f.gradient) {
    const stops = f.gradient.map(colour);
    const one = 'linear-gradient(' + stops.join(', ') + ')';
    return one.length <= 60 ? one : 'linear-gradient(\n      ' + stops.join(',\n      ') + ')';
  }
  if (f.shadow) {
    const layers = f.shadow.map(s => {
      const parts = [px(s.x), px(s.y)];
      if (s.blur != null || s.spread != null) parts.push(px(s.blur || 0));
      if (s.spread != null) parts.push(px(s.spread));
      return (s.inset ? 'inset ' : '') + parts.join(' ') + ' ' + colour(s.color);
    });
    return layers.length === 1 ? layers[0] : '\n      ' + layers.join(',\n      ');
  }
  return colour(f);
}

/* === The block ========================================================== */

function palette(file, lines, withDescriptions) {
  groups(file).forEach(g => {
    lines.push('');
    if (withDescriptions && g.description) lines.push(comment(g.description, 2));
    g.tokens.forEach(({ name, token }) => {
      const v = value(token, g.type);
      if (LEGACY[name]) {
        lines.push('  --' + LEGACY[name] + ': ' + v + ';');
        lines.push('  --' + name + ': var(--' + LEGACY[name] + ');');
      } else {
        lines.push('  --' + name + ': ' + v + ';');
      }
    });
  });
}

function derived(file, theme, lines) {
  groups(file).forEach(g => {
    const own = g.tokens.filter(({ token }) => theme === 'light' || (token && token.dark != null));
    if (!own.length) return;
    lines.push('');
    if (theme === 'light' && g.description) lines.push(comment(g.description, 2));
    own.forEach(({ name, token }) => {
      const f = token && token.light != null ? token[theme] : token;
      const v = formula(f);
      lines.push('  --' + name + ':' + (v[0] === '\n' ? '' : ' ') + v + ';');
    });
  });
}

function glyphs(lines) {
  const dir = path.join(SPEC, 'glyphs');
  fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort().forEach(f => {
    const svg = fs.readFileSync(path.join(dir, f), 'utf8').trim().replace(/</g, '%3C').replace(/>/g, '%3E');
    lines.push('  --glyph-' + f.slice(0, -4) + ': url("data:image/svg+xml,' + svg + '");');
  });
}

function block() {
  const version = fs.readFileSync(path.join(SPEC, 'VERSION'), 'utf8').trim();
  const light = read('palette.light.tokens.json');
  const dark = read('palette.dark.tokens.json');
  const scales = read('scales.tokens.json');
  const rules = read('derived.json');
  const lines = [BEGIN, comment('The tokens of PUDL specification ' + version + '.', 0), '', ':root {'];

  lines.push(comment('These are the values a project theme sets. Everything under "Derived" further down is ' +
    'computed from them, so a new palette is this block and its dark counterpart, and nothing else. Set them ' +
    'on :root and on [data-theme="dark"], because the derived tokens are computed there. --pr is the old name ' +
    'for --positive; a theme that sets --pr still reaches --positive, and new themes set --positive.', 2, 'The palette'));
  palette(light, lines, true);

  lines.push('');
  lines.push(comment('A theme does not change these, except the faces, within the roles the README sets out.',
    2, 'Fixed by the language'));
  palette(scales, lines, true);

  lines.push('');
  lines.push(comment('Glyphs. Every glyph PUDL draws in its chrome is one of these SVG masks, filled with the ' +
    'element\'s own colour, so it looks the same on every platform, can never turn into a colour emoji, ' +
    'and follows the theme.', 2));
  glyphs(lines);

  lines.push('');
  lines.push(comment('These are computed from the palette, so a theme should not need to set any of them. ' +
    'The specification states each as a formula, which is set out here in CSS.', 2, 'Derived'));
  derived(rules, 'light', lines);
  lines.push('}');

  lines.push('');
  lines.push('[data-theme="dark"] {');
  lines.push(comment('The same tokens as the light palette, and the derived tokens whose formula differs ' +
    'in the dark.', 2, 'The dark palette'));
  palette(dark, lines, false);
  derived(rules, 'dark', lines);
  lines.push('}');
  lines.push(END);
  return lines.join('\n');
}

const css = fs.readFileSync(CSS, 'utf8');
const a = css.indexOf(BEGIN), b = css.indexOf(END);
if (a < 0 || b < a) { console.error('pudl.css has no token markers'); process.exit(2); }
const next = css.slice(0, a) + block() + css.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== css) { console.error('FAIL dist/pudl.css\'s token block is not what vendor/pudl-spec produces; run node build/tokens.js'); process.exit(1); }
  console.log('PASS the token block matches vendor/pudl-spec');
} else if (next !== css) {
  fs.writeFileSync(CSS, next);
  console.log('wrote the token block');
} else {
  console.log('the token block was already current');
}
